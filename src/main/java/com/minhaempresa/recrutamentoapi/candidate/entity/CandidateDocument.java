package com.minhaempresa.recrutamentoapi.candidate.entity;

import com.minhaempresa.recrutamentoapi.shared.persistence.UserAuditableEntity;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Table;
import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

/**
 * A file of a candidate (frontend {@code Document}). The content is in the private bucket under
 * {@link #storageKey}, generated by the backend; {@link #fileName} is only the original name. Never
 * changed after upload except by the review.
 */
@Getter
@Entity
@Table(name = "documents")
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class CandidateDocument extends UserAuditableEntity {

    @Column(name = "candidate_id", nullable = false, updatable = false)
    private UUID candidateId;

    @Enumerated(EnumType.STRING)
    @Column(name = "type", nullable = false, length = 20, updatable = false)
    private DocumentType type;

    @Column(name = "file_name", nullable = false, length = 255, updatable = false)
    private String fileName;

    /** Detected from the content. */
    @Column(name = "mime_type", nullable = false, length = 100, updatable = false)
    private String mimeType;

    @Column(name = "size_bytes", nullable = false, updatable = false)
    private long sizeBytes;

    @Column(name = "storage_key", nullable = false, length = 200, updatable = false)
    private String storageKey;

    @Column(name = "sha256", nullable = false, length = 64, updatable = false)
    private String sha256;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 10)
    private DocumentStatus status = DocumentStatus.SUBMITTED;

    /** Number of the BI / NIF / INSS. */
    @Column(name = "reference", length = 20, updatable = false)
    private String reference;

    @Column(name = "expires_at", updatable = false)
    private LocalDate expiresAt;

    @Column(name = "reviewed_by_id")
    private UUID reviewedById;

    @Column(name = "reviewed_at")
    private Instant reviewedAt;

    @Column(name = "rejection_note", length = 500)
    private String rejectionNote;

    @Column(name = "uploaded_at", nullable = false, updatable = false)
    private Instant uploadedAt;

    @SuppressWarnings("java:S107")
    public CandidateDocument(UUID candidateId, DocumentType type, String fileName, String mimeType, long sizeBytes, String storageKey,
                             String sha256, String reference, LocalDate expiresAt, Instant uploadedAt) {
        this.candidateId = candidateId;
        this.type = type;
        this.fileName = fileName;
        this.mimeType = mimeType;
        this.sizeBytes = sizeBytes;
        this.storageKey = storageKey;
        this.sha256 = sha256;
        this.reference = reference;
        this.expiresAt = expiresAt;
        this.uploadedAt = uploadedAt;
    }

    public void review(DocumentStatus decision, String note, UUID reviewerId, Instant now) {
        status = decision;
        rejectionNote = decision == DocumentStatus.REJECTED ? note : null;
        reviewedById = reviewerId;
        reviewedAt = now;
    }
}
