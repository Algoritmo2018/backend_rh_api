-- Message templates (plain text with {{variables}}, never HTML). "Deleted" templates are deactivated;
-- system templates (is_system) are used by the code through their code and cannot be deactivated.
CREATE TABLE message_templates (
    id         UUID PRIMARY KEY,
    code       VARCHAR(60)              NOT NULL,
    name       VARCHAR(80)              NOT NULL,
    channel    VARCHAR(20)              NOT NULL,
    category   VARCHAR(30)              NOT NULL,
    subject    VARCHAR(150),
    body       VARCHAR(4000)            NOT NULL,
    active     BOOLEAN                  NOT NULL DEFAULT TRUE,
    is_system  BOOLEAN                  NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by UUID,
    updated_by UUID,
    CONSTRAINT uk_message_templates_code UNIQUE (code),
    CONSTRAINT fk_message_templates_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_message_templates_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_message_templates_channel CHECK (channel IN ('EMAIL', 'SMS', 'WHATSAPP')),
    CONSTRAINT ck_message_templates_category CHECK (category IN (
        'APPLICATION_RECEIVED', 'INTERVIEW_INVITE', 'INTERVIEW_REMINDER', 'TEST_INVITE',
        'REJECTION', 'OFFER', 'DOCUMENTS_REQUEST', 'GENERAL')),
    CONSTRAINT ck_message_templates_email_subject CHECK (channel <> 'EMAIL' OR subject IS NOT NULL),
    CONSTRAINT ck_message_templates_system_active CHECK (NOT is_system OR active)
);

